def add_section_heading(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.keep_with_next = True
    pPr = p._p.get_or_add_pPr()
    pBdr = parse_xml(f'<w:pBdr {nsdecls("w")}><w:bottom w:val="single" w:sz="6" w:space="3" w:color="{PRIMARY_HEX}"/></w:pBdr>')
    pPr.append(pBdr)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(13.5)
    r.font.color.rgb = PRIMARY_RGB
    return p

def add_sub_heading(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(9)
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.keep_with_next = True
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(11.5)
    r.font.color.rgb = PRIMARY_RGB
    return p

def add_bullet(lead_bold, text):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.space_after = Pt(3)
    if lead_bold:
        rb = p.add_run(lead_bold)
        rb.bold = True
    p.add_run(text)
    return p

def add_prompt_box(title, lines):
    tbl = doc.add_table(rows=1, cols=1)
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = tbl.cell(0, 0)
    set_cell_background(cell, LIGHT_BG)
    set_cell_margins(cell, top=90, bottom=90, left=140, right=140)
    tcPr = cell._tc.get_or_add_tcPr()
    borders = parse_xml(
        f'<w:tcBorders {nsdecls("w")}>'
        f'<w:top w:val="none"/><w:right w:val="none"/><w:bottom w:val="none"/>'
        f'<w:left w:val="single" w:sz="14" w:space="0" w:color="{PRIMARY_HEX}"/>'
        f'</w:tcBorders>'
    )
    tcPr.append(borders)
    p0 = cell.paragraphs[0]
    p0.paragraph_format.space_after = Pt(3)
    rt = p0.add_run(title)
    rt.bold = True
    rt.font.size = Pt(10.5)
    rt.font.color.rgb = PRIMARY_RGB
    for idx, line in enumerate(lines):
        p = cell.add_paragraph()
        p.paragraph_format.space_after = Pt(2 if idx < len(lines)-1 else 0)
        p.paragraph_format.line_spacing = 1.1
        if isinstance(line, tuple):
            r1 = p.add_run(line[0])
            r1.bold = True
            r1.font.size = Pt(10)
            r2 = p.add_run(line[1])
            r2.font.size = Pt(10)
        else:
            r = p.add_run(line)
            r.font.size = Pt(10)
    sp = doc.add_paragraph()
    sp.paragraph_format.space_after = Pt(3)

def add_simple_table(headers, rows, col_widths=None):
    tbl = doc.add_table(rows=len(rows) + 1, cols=len(headers))
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    set_table_borders(tbl)
    hdr_row = tbl.rows[0]
    trPr = hdr_row._tr.get_or_add_trPr()
    trPr.append(parse_xml(f'<w:tblHeader {nsdecls("w")}/>'))
    for i, h_text in enumerate(headers):
        cell = hdr_row.cells[i]
        set_cell_background(cell, PRIMARY_HEX)
        set_cell_margins(cell, top=90, bottom=90, left=100, right=100)
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        p = cell.paragraphs[0]
        p.paragraph_format.space_after = Pt(0)
        r = p.add_run(h_text)
        r.bold = True
        r.font.size = Pt(10)
        r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
    for r_idx, r_data in enumerate(rows):
        row = tbl.rows[r_idx + 1]
        trPr_r = row._tr.get_or_add_trPr()
        trPr_r.append(parse_xml(f'<w:cantSplit {nsdecls("w")}/>'))
        bg = "FFFFFF" if r_idx % 2 == 0 else "F9FAFB"
        for c_idx, val in enumerate(r_data):
            cell = row.cells[c_idx]
            set_cell_background(cell, bg)
            set_cell_margins(cell, top=80, bottom=80, left=100, right=100)
            cell.vertical_alignment = WD_ALIGN_VERTICAL.TOP
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.line_spacing = 1.1
            r = p.add_run(val)
            r.font.size = Pt(10)
            if c_idx == 0:
                r.bold = True
    if col_widths:
        for row in tbl.rows:
            for idx, w in enumerate(col_widths):
                row.cells[idx].width = Inches(w)
    sp = doc.add_paragraph()
    sp.paragraph_format.space_after = Pt(3)
    return tbl

